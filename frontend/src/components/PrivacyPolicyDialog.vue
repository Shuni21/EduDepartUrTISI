<script setup lang="ts">
import { nextTick, onBeforeUnmount, ref, watch } from 'vue'

const props = defineProps<{
  modelValue: boolean
}>()

const emit = defineEmits<{
  (event: 'update:modelValue', value: boolean): void
}>()

const dialogElement = ref<HTMLElement | null>(null)
const closeButton = ref<HTMLButtonElement | null>(null)
let previouslyFocusedElement: HTMLElement | null = null

const close = () => {
  emit('update:modelValue', false)
}

const handleKeydown = (event: KeyboardEvent) => {
  if (event.key === 'Escape') {
    event.preventDefault()
    close()
    return
  }

  if (event.key !== 'Tab' || !dialogElement.value) {
    return
  }

  const focusableElements = dialogElement.value.querySelectorAll<HTMLElement>(
    'button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])',
  )
  const firstElement = focusableElements.item(0)
  const lastElement = focusableElements.item(focusableElements.length - 1)

  if (!firstElement || !lastElement) {
    event.preventDefault()
    return
  }

  if (event.shiftKey && (document.activeElement === firstElement || !dialogElement.value.contains(document.activeElement))) {
    event.preventDefault()
    lastElement.focus()
  } else if (!event.shiftKey && (document.activeElement === lastElement || !dialogElement.value.contains(document.activeElement))) {
    event.preventDefault()
    firstElement.focus()
  }
}

watch(
  () => props.modelValue,
  async (isOpen) => {
    if (isOpen) {
      previouslyFocusedElement = document.activeElement instanceof HTMLElement
        ? document.activeElement
        : null
      window.addEventListener('keydown', handleKeydown)
      await nextTick()

      if (props.modelValue) {
        closeButton.value?.focus()
      }

      return
    }

    window.removeEventListener('keydown', handleKeydown)
    previouslyFocusedElement?.focus()
    previouslyFocusedElement = null
  },
)

onBeforeUnmount(() => {
  window.removeEventListener('keydown', handleKeydown)
  previouslyFocusedElement?.focus()
})
